import { expect, test, type Page } from "@playwright/test"
import { testOrigins } from "../scripts/dev-environment.mjs"

async function story(page: Page, id: string) {
  await page.goto(`${testOrigins().stories}/iframe.html?id=project-dashboard-${id}&viewMode=story`)
  await expect(page.locator("main")).toBeVisible()
}

test("template creation preserves compatible options and resets renderer-specific choices", async ({
  page
}, testInfo) => {
  await story(page, "create-project--starter-kits")
  await page.getByRole("button", { name: "Select Three.js", exact: true }).click()
  await page.getByRole("button", { name: "Continue", exact: true }).click()
  await page.getByLabel("Project name", { exact: true }).fill("Canyon Circuit")
  await expect(page.locator("#creation-name-hint")).toHaveText("Folder name: canyon-circuit")
  await page.locator("summary").filter({ hasText: "Customize your stack" }).click()
  await page.getByRole("radio", { name: "Rapier 3D", exact: true }).check()
  await page.getByRole("radio", { name: "bitECS", exact: true }).check()
  await expect(page.getByRole("checkbox", { name: "Storybook", exact: true })).toBeDisabled()
  await expect(page.getByRole("checkbox", { name: "Playwright", exact: true })).toBeDisabled()
  await expect(page.getByRole("radio", { name: "React", exact: true })).toBeDisabled()
  await page.getByRole("button", { name: "Change", exact: true }).click()
  await page.getByRole("button", { name: "Select Phaser", exact: true }).click()
  await page.getByRole("button", { name: "Continue", exact: true }).click()
  await expect(page.getByLabel("Project name", { exact: true })).toHaveValue("Canyon Circuit")
  await page.locator("summary").filter({ hasText: "Customize your stack" }).click()
  await expect(page.getByRole("radio", { name: "Rapier 3D", exact: true })).toHaveCount(0)
  await expect(page.getByRole("radio", { name: "bitECS", exact: true })).toBeChecked()
  await page.getByRole("radio", { name: "Arcade Physics", exact: true }).check()
  await page.getByRole("button", { name: "Continue", exact: true }).click()
  await page.getByRole("checkbox", { name: "Enable Sandbox", exact: true }).check()
  await expect(page.getByRole("region", { name: "Sandbox regions", exact: true })).toHaveCount(0)
  await expect(page.getByTestId("estimated-total")).toHaveText("$5.00/mo")
  await page.getByRole("button", { name: "Continue", exact: true }).click()
  await expect(page.locator("main")).toContainText("Arcade Physics")
  await expect(page.locator("code").filter({ hasText: "npx spawn init canyon-circuit" })).toContainText(
    "--template phaser --with vitest,bitecs --physics arcade"
  )
  await page.screenshot({ path: `work/creation-review-${testInfo.project.name}.png`, fullPage: true })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.getByRole("button", { name: "Create project", exact: true }).click()
  await page.getByRole("button", { name: "Open project", exact: true }).click()
  await expect(page.getByRole("heading", { name: "Canyon Circuit", exact: true })).toBeVisible()
  await expect(page.getByText("No version deployed", { exact: true })).toBeVisible()
  await expect(page.getByRole("region", { name: "Production deployment", exact: true })).toContainText("Phaser")
})

test("creation keeps failed choices and blocks read-only creation", async ({ page }) => {
  await story(page, "create-project--creation-failed")
  await page.getByRole("button", { name: "Create project", exact: true }).click()
  await expect(page.getByRole("alert")).toContainText("Your choices are saved here")
  await expect(page.getByRole("heading", { name: "Emberfall", exact: true })).toBeVisible()
  await page.getByRole("button", { name: "Edit", exact: true }).click()
  await expect(page.getByLabel("Project name", { exact: true })).toHaveValue("Emberfall")
  await story(page, "create-project--read-only")
  await expect(page.getByRole("button", { name: "Continue", exact: true })).toBeDisabled()
  await expect(page.getByRole("button", { name: "Select PixiJS", exact: true })).toBeDisabled()
})

test("domain setup requires DNS and HTTPS before choosing a primary address", async ({ page }, testInfo) => {
  await story(page, "domains--connect-domain")
  let dialog = page.getByRole("dialog", { name: "Connect a domain", exact: true })
  await dialog.getByLabel("Domain", { exact: true }).fill("https://play.example.com/path")
  await dialog.getByRole("button", { name: "Continue to DNS", exact: true }).click()
  await expect(dialog.getByRole("alert")).toContainText("without https://")
  await dialog.getByLabel("Domain", { exact: true }).fill("play.emberfall.example.com")
  await dialog.getByRole("button", { name: "Continue to DNS", exact: true }).click()
  dialog = page.getByRole("dialog", { name: "play.emberfall.example.com", exact: true })
  await expect(dialog).toContainText("Awaiting DNS")
  await expect(dialog.getByRole("button", { name: "Set as primary", exact: true })).toHaveCount(0)
  await expect(dialog.getByRole("button", { name: "Copy CNAME value", exact: true })).toBeVisible()
  await page.screenshot({ path: `work/domain-dns-${testInfo.project.name}.png`, fullPage: true })
  await dialog.getByRole("button", { name: "Check status", exact: true }).click()
  await expect(dialog).toContainText("Issuing certificate")
  await expect(dialog.getByRole("button", { name: "Set as primary", exact: true })).toHaveCount(0)
  await dialog.getByRole("button", { name: "Check status", exact: true }).click()
  await dialog.getByRole("button", { name: "Set as primary", exact: true }).click()
  await dialog.getByRole("button", { name: "Confirm primary domain", exact: true }).click()
  await expect(dialog.getByText("Primary domain", { exact: true })).toBeVisible()
  await dialog.getByRole("button", { name: "Close", exact: true }).click()
  await page.getByRole("button", { name: "Clockwork Courier", exact: true }).click()
  await expect(page.getByRole("region", { name: "Production deployment" }).getByRole("link").first()).toHaveAttribute(
    "href",
    "https://play.emberfall.example.com"
  )
  await page.getByRole("button", { name: "Manage domains", exact: true }).click()
  await page.getByRole("button", { name: "Manage play.emberfall.example.com", exact: true }).click()
  await dialog.getByRole("button", { name: "Disconnect", exact: true }).click()
  await expect(dialog).toContainText("Your versions and game data are kept")
  await dialog.getByRole("button", { name: "Disconnect domain", exact: true }).click()
  await expect(dialog).toHaveCount(0)
  await expect(page.getByRole("heading", { name: "Give your game its own address", exact: true })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
})

test("domains remain scoped to environments and failed requests retain the hostname", async ({ page }) => {
  await story(page, "domains--connected")
  await page.getByRole("tab", { name: "Sandbox", exact: true }).click()
  await expect(page.getByRole("heading", { name: "test.clockwork.example.com", exact: true })).toBeVisible()
  await expect(page.getByRole("heading", { name: "play.clockwork.example.com", exact: true })).toHaveCount(0)
  await story(page, "domains--request-failed")
  const dialog = page.getByRole("dialog", { name: "Connect a domain", exact: true })
  await dialog.getByLabel("Domain", { exact: true }).fill("play.retry.example.com")
  await dialog.getByRole("button", { name: "Continue to DNS", exact: true }).click()
  await expect(dialog.getByRole("alert")).toContainText("Your entries are preserved")
  await expect(dialog.getByLabel("Domain", { exact: true })).toHaveValue("play.retry.example.com")
  await story(page, "domains--read-only")
  await expect(page.getByRole("dialog").getByRole("button", { name: "Check status", exact: true })).toBeDisabled()
  await expect(page.getByRole("dialog").getByRole("button", { name: "Disconnect", exact: true })).toBeDisabled()
})
