import { expect, test } from "@playwright/test"

test("regional estimates retain each machine and charge the bundle once", async ({ page }) => {
  await page.goto("/cloud#compute-pricing")
  const pricing = page.locator("#compute-pricing")
  const total = pricing.locator(".p-estimate-total")
  await expect(total).toHaveText("$30.44")
  await pricing.getByRole("button", { name: "Add region", exact: true }).click()
  const amsterdam = pricing.getByRole("article", { name: "Amsterdam", exact: true })
  const newJersey = pricing.getByRole("article", { name: "New Jersey", exact: true })
  await expect(amsterdam.getByRole("heading", { name: "Amsterdam", exact: true })).toBeFocused()
  await expect(newJersey).toBeVisible()
  await expect(total).toHaveText("$50.88")
  await amsterdam.getByRole("combobox", { name: "Machine size", exact: true }).click()
  await page.getByRole("option", { name: "2 vCPU / 4 GB RAM", exact: true }).click()
  await amsterdam.getByRole("spinbutton", { name: "Production hours / month" }).fill("100")
  await amsterdam.getByRole("spinbutton", { name: "Sandbox hours / month" }).fill("20")
  await expect(total).toHaveText("$36.65")
  await pricing.getByRole("combobox", { name: "Server location", exact: true }).click()
  await expect(page.getByRole("option", { name: "New Jersey, US", exact: true })).toHaveCount(0)
  await expect(page.getByRole("option", { name: "Amsterdam, NL", exact: true })).toHaveCount(0)
  await page.keyboard.press("Escape")
  await expect(newJersey.getByRole("spinbutton", { name: "Production hours / month" })).toHaveValue("730")
  await expect(newJersey.getByRole("combobox", { name: "Machine size", exact: true })).toContainText(
    "1 vCPU / 2 GB RAM"
  )
  await expect(amsterdam.getByRole("spinbutton", { name: "Production hours / month" })).toHaveValue("100")
  await amsterdam.getByRole("spinbutton", { name: "Sandbox hours / month" }).fill("")
  await expect(total).toHaveCount(0)
  await expect(pricing.getByRole("alert")).toContainText("Amsterdam")
  await expect(total).toHaveCount(0)
  await pricing.getByRole("button", { name: "Remove Amsterdam region" }).click()
  await expect(pricing.getByRole("button", { name: "Add region", exact: true })).toBeFocused()
  await expect(total).toHaveText("$30.44")
  await expect(pricing.getByRole("button", { name: "Remove New Jersey region" })).toBeDisabled()
  await pricing.getByRole("combobox", { name: "Server location", exact: true }).click()
  await page.getByRole("option", { name: "São Paulo, BR", exact: true }).click()
  await pricing.getByRole("button", { name: "Add region", exact: true }).click()
  await pricing.getByRole("button", { name: "Remove New Jersey region" }).click()
  const saoPaulo = pricing.getByRole("article", { name: "São Paulo", exact: true })
  await saoPaulo.getByRole("combobox", { name: "Machine size", exact: true }).click()
  await page.getByRole("option", { name: "2 vCPU / 4 GB RAM", exact: true }).click()
  await saoPaulo.getByRole("spinbutton", { name: "Sandbox hours / month" }).fill("100")
  await expect(total).toHaveText("$76.01")
})

test("cloud animations play, pause, replay, and stop outside the viewport", async ({ page }) => {
  await page.emulateMedia({ reducedMotion: "no-preference" })
  await page.goto("/cloud")
  const workflow = page.locator(".mk-release-walkthrough")
  await workflow.getByRole("tab", { name: "Test", exact: true }).click()
  const checks = workflow.locator(".mk-checks-scene")
  await checks.scrollIntoViewIfNeeded()
  const progress = checks.getByRole("progressbar")
  await expect(progress).toHaveAttribute("value", "5", { timeout: 15000 })
  await expect(checks.getByText("All checks passed")).toBeVisible()
  await checks.getByRole("button", { name: "Pause checks animation", exact: true }).click()
  await expect(checks).toHaveAttribute("data-running", "false")
  await page.waitForTimeout(1900)
  await expect(progress).toHaveAttribute("value", "5")
  await checks.getByRole("button", { name: "Replay checks animation", exact: true }).click()
  await expect(progress).toHaveAttribute("value", "0")
  await expect(checks.locator('[data-state="running"]')).toHaveCount(1)
  await expect(checks.locator('[data-state="queued"]')).toHaveCount(4)
  await page.locator("#compute-pricing").scrollIntoViewIfNeeded()
  await expect(checks).toHaveAttribute("data-running", "false")
  const offscreenProgress = await progress.getAttribute("value")
  await page.waitForTimeout(1900)
  await expect(progress).toHaveAttribute("value", offscreenProgress!)
  await checks.scrollIntoViewIfNeeded()
  await expect(checks).toHaveAttribute("data-running", "true")
  await page.emulateMedia({ reducedMotion: "reduce" })
  await expect(checks).toHaveAttribute("data-running", "false")
  await expect(progress).toHaveAttribute("value", "5")
  await expect(checks.getByRole("button", { name: /animation/ })).toHaveCount(0)
})

test("deployment stages, monitoring details, and orbit services are usable without motion", async ({ page }) => {
  await page.emulateMedia({ reducedMotion: "reduce" })
  await page.goto("/cloud")
  const workflow = page.locator(".mk-release-walkthrough")
  await workflow.getByRole("tab", { name: "Deploy", exact: true }).click()
  await workflow.getByRole("button", { name: "Merge", exact: true }).click()
  await expect(workflow.locator(".mk-deploy-caption")).toContainText("merge triggers the configured CI workflow")
  await expect(workflow.locator(".mk-production-node")).toContainText("v1.1")
  await workflow.getByRole("button", { name: "Staging", exact: true }).click()
  await expect(workflow.locator(".mk-map-node").first()).toContainText("v1.2")
  await expect(workflow.locator(".mk-production-node")).toContainText("v1.1")
  await workflow.getByRole("button", { name: "Promote", exact: true }).click()
  await expect(workflow.locator(".mk-production-node")).toContainText("v1.2")
  await workflow.getByRole("button", { name: "Rollback", exact: true }).click()
  await expect(workflow.locator(".mk-production-node")).toContainText("v1.1")
  await expect(workflow.locator(".mk-deploy-caption")).toContainText("Player data is not rolled back")
  await workflow.getByRole("tab", { name: "Monitor", exact: true }).click()
  const issue = workflow.getByRole("button", { name: /Player could not resume level/ })
  await issue.click()
  await expect(issue).toHaveAttribute("aria-expanded", "true")
  await expect(workflow.locator(".mk-issue-detail")).toContainText("preferred AI agent")
  await page.getByRole("button", { name: "Explore Leaderboards", exact: true }).click()
  await expect(page.locator("#services").getByRole("tab", { name: "Leaderboards", exact: true })).toHaveAttribute(
    "aria-selected",
    "true"
  )
  await expect(page.locator("#services").getByRole("tabpanel")).toContainText("2,450 points")
  expect(
    await page
      .locator(".mk-service-satellite")
      .first()
      .evaluate((element) => getComputedStyle(element).animationName)
  ).toBe("none")
  await page.locator("#services").getByRole("tab", { name: "Cloud saves", exact: true }).click()
  await expect(page.getByRole("button", { name: "Explore Cloud saves", exact: true })).toHaveAttribute(
    "aria-pressed",
    "true"
  )
  await expect(page.locator("#services").getByRole("tabpanel")).toContainText("Saved to cloud")
  await page.setViewportSize({ width: 320, height: 800 })
  for (const name of ["Create", "Test", "Deploy", "Monitor"]) {
    await workflow.getByRole("tab", { name, exact: true }).click()
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  }
  await page.locator("#services").scrollIntoViewIfNeeded()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  expect(await page.locator(".mk-cloud").innerText()).not.toMatch(/[—•·]/)
})
