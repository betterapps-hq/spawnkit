test("environment cards can move and preserve their position through inspection", async ({ page }, info) => {
  await open(page)
  const card = page.locator('.react-flow__node[data-id="staging"]')
  const header = card.locator(".dm-environment-title strong")
  await header.scrollIntoViewIfNeeded()
  const before = await card.getAttribute("style")
  const bounds = (await header.boundingBox())!
  await page.mouse.move(bounds.x + bounds.width / 2, bounds.y + bounds.height / 2)
  await page.mouse.down()
  await page.mouse.move(
    bounds.x + bounds.width / 2 + (info.project.name === "mobile" ? 15 : 65),
    bounds.y + bounds.height / 2 + 45,
    { steps: 12 }
  )
  await page.mouse.up()
  await expect(card).not.toHaveAttribute("style", before!)
  const moved = await card.getAttribute("style")
  await expect(page.getByRole("dialog")).toHaveCount(0)
  await inspect(page, "staging")
  await close(page)
  await expect(card).toHaveAttribute("style", moved!)
  await page.getByRole("button", { name: "Reset layout" }).click()
  await expect(card).toHaveAttribute("style", before!)
})

