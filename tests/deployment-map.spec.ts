import { test, expect, type Page } from "@playwright/test"
import { testOrigins } from "../scripts/dev-environment.mjs"
const base = testOrigins().stories
async function open(page: Page, story = "infrastructure") {
  await page.goto(`${base}/iframe.html?id=project-dashboard-deployment-map--${story}&viewMode=story`)
  await expect(page.getByRole("heading", { name: "Deployments", exact: true })).toBeVisible()
}
async function choose(page: Page, label: string, value: string) {
  await page.getByRole("combobox", { name: label, exact: true }).click()
  await page.getByRole("option", { name: value, exact: true }).click()
  await expect(page.getByRole("combobox", { name: label, exact: true })).toBeFocused()
}
async function inspect(page: Page, id: string) {
  const node = page.locator(`.react-flow__node[data-id="${id}"]`)
  // React Flow hides new nodes until measurement; hidden nodes cannot receive focus.
  await expect(node).toBeVisible()
  await node.focus()
  await expect(node).toBeFocused()
  await node.press("Enter")
  await expect(page.getByRole("dialog")).toBeVisible()
}
async function close(page: Page) {
  await page.keyboard.press("Escape")
  await expect(page.getByRole("dialog")).toHaveCount(0)
}
