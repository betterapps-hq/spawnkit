import { expect, test, type Page } from "@playwright/test"
import { testOrigins } from "../scripts/dev-environment.mjs"
const story = `${testOrigins().stories}/iframe.html?id=project-dashboard-navigation--`
async function openSidebar(page: Page) {
  if (page.viewportSize()!.width < 1024)
    await page.getByRole("button", { name: "Expand navigation", exact: true }).click()
}
async function openAccount(page: Page) {
  await openSidebar(page)
  await page.getByRole("button", { name: "Open user menu", exact: true }).click()
}

test("sidebar keeps an icon rail on small screens and remembers the desktop preference", async ({ page }, testInfo) => {
  if (page.viewportSize()!.width < 1024)
    await page.addInitScript(() => localStorage.setItem("spawn:sidebar", "expanded"))
  await page.goto(`${story}expanded&viewMode=story`)
  const navigation = page.getByRole("navigation", { name: "Project navigation", exact: true })
  if (page.viewportSize()!.width < 1024) {
    await expect(navigation).toBeVisible()
    const rail = page.locator('[data-slot="sidebar"][data-state="collapsed"]')
    await expect(rail).toBeVisible()
    const logs = navigation.getByRole("button", { name: "Logs", exact: true })
    await expect(logs.locator("svg")).toBeVisible()
    await expect.poll(async () => (await logs.boundingBox())!.width).toBeLessThan(48)
    await logs.click()
    await expect(rail).toBeVisible()
    await expect(page.getByRole("heading", { name: "Logs", exact: true })).toBeVisible()
    await openSidebar(page)
    const expanded = page.getByRole("dialog", { name: "Project navigation", exact: true })
    await expect(expanded).toBeVisible()
    await expanded.getByRole("button", { name: "Overview", exact: true }).click()
    await expect(expanded).not.toBeVisible()
    await expect(rail).toBeVisible()
    await page.reload()
    await expect(rail).toBeVisible()
    await expect(navigation).toBeVisible()
    await page.getByRole("button", { name: "Open user menu", exact: true }).click()
    await expect(page.getByRole("menuitemradio", { name: "System", exact: true })).toBeVisible()
    await page.keyboard.press("Escape")
    await page.getByRole("button", { name: "Switch project: Thornwatch", exact: true }).click()
    await expect(page.getByRole("menuitem", { name: "Iron Frontier", exact: true })).toBeVisible()
    await page.keyboard.press("Escape")
  } else {
    await page.getByRole("button", { name: "Collapse sidebar", exact: true }).click()
    await expect(page.locator('[data-slot="sidebar"][data-state="collapsed"]')).toBeVisible()
    const logs = navigation.getByRole("button", { name: "Logs", exact: true })
    await expect(logs.locator("svg")).toBeVisible()
    await expect.poll(async () => (await logs.boundingBox())!.width).toBeLessThan(48)
    await logs.hover()
    await expect(page.getByRole("tooltip", { name: "Logs", exact: true })).toBeVisible()
    await logs.click()
    await expect(page.getByRole("heading", { name: "Logs", exact: true })).toBeVisible()
    await page.reload()
    await expect(page.getByRole("button", { name: "Expand sidebar", exact: true })).toBeVisible()
    await page.getByRole("button", { name: "Expand sidebar", exact: true }).press("Control+b")
    await expect(page.getByRole("button", { name: "Collapse sidebar", exact: true })).toBeVisible()
    const viewport = page.viewportSize()!
    await page.setViewportSize({ width: 820, height: viewport.height })
    await expect(page.locator('[data-slot="sidebar"][data-state="collapsed"]')).toBeVisible()
    await expect(navigation.getByRole("button", { name: "Logs", exact: true })).toBeVisible()
    await page.setViewportSize(viewport)
    await expect(page.getByRole("button", { name: "Collapse sidebar", exact: true })).toBeVisible()
  }
  const footer = page.locator('[data-slot="sidebar-footer"]')
  await expect(footer.getByRole("button", { name: "Open user menu" })).toBeVisible()
  const box = await footer.boundingBox()
  expect(box!.y).toBeGreaterThan(page.viewportSize()!.height / 2)
  await expect(page.locator("header").getByRole("button", { name: "Open user menu" })).toHaveCount(0)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: `work/sidebar-${testInfo.project.name}.png`, animations: "disabled" })
})

test("theme defaults to Dark, supports System and persists an explicit choice", async ({ page, context }) => {
  await page.emulateMedia({ colorScheme: "light" })
  await page.goto(`${story}expanded&viewMode=story`)
  await expect(page.locator("html")).toHaveClass(/dark/)
  await openAccount(page)
  await expect(page.getByRole("menuitemradio", { name: "Dark", exact: true })).toBeChecked()
  await page.getByRole("menuitemradio", { name: "System", exact: true }).click()
  await expect(page.locator("html")).not.toHaveClass(/dark/)
  await page.emulateMedia({ colorScheme: "dark" })
  await expect(page.locator("html")).toHaveClass(/dark/)
  await page.emulateMedia({ colorScheme: "light" })
  await expect(page.locator("html")).not.toHaveClass(/dark/)
  await page.getByRole("menuitemradio", { name: "Dark", exact: true }).click()
  await expect(page.locator("html")).toHaveClass(/dark/)
  await expect(page.getByRole("menuitemradio", { name: "Dark", exact: true })).toBeChecked()
  await page.reload()
  await expect(page.locator("html")).toHaveClass(/dark/)
  const other = await context.newPage()
  await other.goto(`${story}expanded&viewMode=story`)
  await expect(other.locator("html")).toHaveClass(/dark/)
  await openAccount(page)
  await page.getByRole("menuitemradio", { name: "Light", exact: true }).click()
  await expect(other.locator("html")).not.toHaveClass(/dark/)
  await page.getByRole("menuitemradio", { name: "Light", exact: true }).press("ArrowRight")
  await page.keyboard.press("Enter")
  await expect(page.getByRole("menuitemradio", { name: "Dark", exact: true })).toBeChecked()
  await expect(page.getByRole("menuitem", { name: "Account", exact: true })).toBeEnabled()
  await expect(page.getByRole("menuitem", { name: "Sign out", exact: true })).toBeEnabled()
  await other.close()
})

test("notification inbox filters, marks read, and opens the related project", async ({ page }) => {
  await page.goto(`${story}notifications&viewMode=story`)
  await page.getByRole("button", { name: "Notifications, 2 unread", exact: true }).click()
  const panel = page.getByRole("dialog", { name: "Notifications", exact: true })
  await expect(panel.getByText("Production updated", { exact: true })).toBeVisible()
  await panel.getByRole("tab", { name: "Unread 2", exact: true }).click()
  await expect(panel.getByText("Production updated", { exact: true })).not.toBeVisible()
  await panel.getByRole("button", { name: "Mark Version build failed as read", exact: true }).click()
  await expect(panel.getByText("Version build failed", { exact: true })).not.toBeVisible()
  await panel.getByRole("button", { name: /PR preview is ready Review/ }).click()
  await expect(panel).not.toBeVisible()
  await expect(page.getByRole("heading", { name: "Deployments", exact: true })).toBeVisible()
  await page.getByRole("button", { name: "Notifications", exact: true }).click()
  await expect(panel.getByText("No unread notifications.", { exact: true })).toBeVisible()
  await panel.getByRole("tab", { name: "All", exact: true }).click()
  await expect(panel.getByText("Production updated", { exact: true })).toBeVisible()
  await expect(panel.getByRole("button", { name: "Mark all as read", exact: true })).toBeDisabled()
})

test("empty notifications and unavailable storage remain usable", async ({ page }) => {
  await page.addInitScript(() => {
    Storage.prototype.setItem = () => {
      throw new DOMException("Blocked", "SecurityError")
    }
    Storage.prototype.getItem = () => {
      throw new DOMException("Blocked", "SecurityError")
    }
  })
  await page.goto(`${story}expanded&viewMode=story`)
  await page.getByRole("button", { name: "Notifications", exact: true }).click()
  await expect(page.getByText("You're all caught up", { exact: true })).toBeVisible()
  await page.keyboard.press("Escape")
  await expect(page.getByRole("dialog", { name: "Notifications", exact: true })).toHaveCount(0)
  await expect(page.getByRole("button", { name: "Notifications", exact: true })).toBeFocused()
  await openAccount(page)
  await page.getByRole("menuitemradio", { name: "Dark", exact: true }).click()
  await expect(page.locator("html")).toHaveClass(/dark/)
})

test("header quick navigation searches projects and pages with keyboard support", async ({ page }, testInfo) => {
  await page.goto(`${story}expanded&viewMode=story`)
  const header = page.locator("header")
  await expect(header.getByRole("button", { name: "Thornwatch", exact: true })).toBeVisible()
  await header.getByRole("button", { name: "Search projects and pages", exact: true }).click()
  const dialog = page.getByRole("dialog", { name: "Quick navigation", exact: true })
  await dialog.getByLabel("Search navigation").fill("domains")
  await dialog.getByLabel("Search navigation").press("ArrowDown")
  await expect(dialog.getByRole("button", { name: "Domains", exact: true })).toBeFocused()
  await page.keyboard.press("Enter")
  await expect(dialog).not.toBeVisible()
  await expect(page.getByRole("heading", { name: "Domains", exact: true })).toBeVisible()
  await page.keyboard.press("Control+k")
  await dialog.getByLabel("Search navigation").fill("iron frontier")
  await expect(dialog.getByRole("button", { name: "Iron Frontier", exact: true })).toBeVisible()
  await page.screenshot({ path: `work/header-navigation-${testInfo.project.name}.png`, animations: "disabled" })
  await dialog.getByLabel("Search navigation").press("Enter")
  await expect(page.getByRole("heading", { name: "Iron Frontier", exact: true })).toBeVisible()
  await header.getByRole("button", { name: "Search projects and pages", exact: true }).click()
  await dialog.getByLabel("Search navigation").fill("no-such-project")
  await expect(dialog.getByText("No matching projects or pages.", { exact: true })).toBeVisible()
  await page.keyboard.press("Escape")
  await expect(header.getByRole("button", { name: "Search projects and pages", exact: true })).toBeFocused()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
})
