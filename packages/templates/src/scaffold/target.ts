import { defineTarget, type Contribution, type TargetContext } from "@buildkitgg/scaffolder"
import { defaultCover, listingSchema } from "../listing"
import { listingConfigSource, listingPluginSource } from "../listing-config"
import { localDevelopmentFiles } from "../local-development"
import { inputSource } from "../simulation"
import { mainSources, runtimeSource, type Renderer } from "./game"

const json = (value: unknown) => JSON.stringify(value, null, 2) + "\n"

const titles: Record<Renderer, string> = { pixi: "PixiJS", phaser: "Phaser", babylon: "Babylon.js", three: "Three.js" }
const packages: Record<Renderer, [string, ...string[]]> = {
  pixi: ["pixi.js"],
  phaser: ["phaser"],
  babylon: ["@babylonjs/core"],
  three: ["three", "@types/three"]
}

/** Where the game's points render. Every renderer's `src/main.ts` imports it through `spawnkit/runtime.ts`. */
const gameFile = "spawnkit/game.ts"

export function isRenderer(value: string): value is Renderer {
  return value in titles
}

function seed(path: string, content: string): Contribution {
  return { kind: "file", path, content, ownership: "seed" }
}
function owned(path: string, content: string): Contribution {
  return { kind: "file", path, content, ownership: "owned" }
}
function sample(path: string, content: string): Contribution {
  return { kind: "file", path, content, ownership: "sample" }
}
function set(path: string, pointer: string, value: unknown): Contribution {
  return { kind: "json", path, pointer, op: "set", value }
}

function readme(name: string, renderer: Renderer) {
  return `# ${name}

${titles[renderer]} single-player game generated with SpawnKit.

## Run locally

Requires Node.js 24+ and pnpm 12.

\`\`\`sh
pnpm install
pnpm dev
\`\`\`

Use the arrow keys to collect gold. Edit src/main.ts to make the game your own.

## Verify and build

\`\`\`sh
pnpm lint
pnpm build
\`\`\`

Add-ons that add checks, such as tests, describe them in docs/. The production frontend is written to dist/. This
project has no hosted backend. Use the SpawnKit CLI to link the project and deploy its frontend.

Commit the pnpm-lock.yaml generated by pnpm install. Dependencies use exact versions; the lockfile also records
transitive versions.

## What the project is made of

spawn.jsonc records the renderer and the add-ons you chose. Run spawn add to add one, spawn add <add-on> --replace
<add-on> to swap one, and spawn upgrade to move to a newer SpawnKit catalog. spawn keeps your edits: it merges them,
or asks. Files under spawnkit/ are generated, so change them through spawn instead of editing them.

Add-ons join the game through spawnkit/game.ts: each one is a system that src/main.ts starts with the renderer and
runs every frame. A UI system can pause the game, and a physics system steps its own world.

## Game listing

Edit spawnkit.config.ts with the included defineConfig() helper to set your title, description, genre, dimension (2D
or 3D), coverPath, and optional trailerPath. TypeScript checks required fields and genre/dimension choices; the helper
validates text lengths and paths at build time. The Vite plugin emits spawnkit.config.json into dist. For JSON, replace
the TypeScript file with spawnkit.config.json at the project root. Both formats describe the same listing; the plugin
detects and validates either one automatically. Use only one source. Genre defaults to Arcade; choose the best match
before publishing. A 1280×720 editable default illustration is included at public/media/cover.svg. Replace it with your
own PNG, JPEG, WebP, or SVG cover (up to 1 MiB) and update coverPath. Optional gameplay video supports MP4/WebM up to 2
MiB and 60 seconds. SpawnKit automatically creates a bounded WebP cover and a silent, compressed MP4 preview of the first
eight seconds, at most 640 pixels on either side. Start your clip on active gameplay; the platform does not choose
highlights or detect title screens. Oversized or invalid listing media is omitted with a build-log warning; the game
can still deploy. Paths are relative to the build root, without public/ or a leading slash. Vite copies these files into
dist automatically. The CLI checks available public media before uploading without executing the config. Dynamic or
build-generated media is checked on SpawnKit after the build. Platform validation and compression remain authoritative.

## Local domains

Run pnpm exec dev-domains urls for exact app, Storybook, and isolated E2E origins. BuildKit dev-domains starts or
reuses Portless for trusted HTTPS and assigns backend ports. Every template includes it as a pinned development
dependency. Unlinked projects use <project>.local.spawnkit.games; Git worktrees add their folder name. Run pnpm exec
dev-domains doctor to diagnose DNS, proxy, and certificate setup. The CLI saves your verified hostname when you link a
project. You can also set SPAWN_GAME_DOMAIN to your assigned project hostname (for example emberfall.spawnkit.games) to
use local.emberfall.spawnkit.games after domain provisioning. Set SPAWN_LOCAL_NAME to give an independent clone its own
address. Configure endpoint names in dev-domains.config.mjs. First-time certificate trust may need interactive machine
setup. Use pnpm exec vite for a plain Vite server. Automated tests use loopback by default; set SPAWN_E2E_HTTPS=1 to
test the named HTTPS endpoint after machine setup. Register exact OAuth callbacks and telemetry origins; public webhooks
require a separately configured tunnel and server receiver. No shared wildcard cookies or browser-side webhook secrets.
`
}

function agents(name: string, renderer: Renderer) {
  return `# ${name}

Standalone ${titles[renderer]} browser game. Use Node.js 24+ and pnpm 12.

- Read spawn.jsonc for the add-ons this project uses, and package.json for its commands.
- Install with pnpm install; keep pnpm-lock.yaml. Run pnpm lint and pnpm build after changes, and pnpm test / pnpm e2e only when those scripts exist. Test scripts prepare Chromium automatically outside CI. If test:setup exists, use pnpm test:setup --with-deps before tests in CI. When the setup script exists, pnpm run setup prepares local HTTPS and Chromium; certificate trust may prompt.
- Edit src/main.ts and the add-on sources in src/. Preserve existing user files, saves and artwork.
- Don't edit files under spawnkit/: they're generated. Run pnpm dlx @spawnkit/cli add, config or upgrade to change them, with --dry-run first.
- pnpm dev uses named local HTTPS; pnpm exec dev-domains doctor diagnoses setup. pnpm exec vite provides a plain local server.
- Keep this project standalone. Never place secrets in VITE_ variables or public assets.
- Local development requires no account. Publish only when requested, to the confirmed project. See https://spawnkit.cloud/docs/publishing and https://spawnkit.cloud/auth.md.
- Run the CLI with pnpm dlx @spawnkit/cli. Use --help for commands and --dry-run before mutations. Remote publishing requires explicit project approval; see https://spawnkit.cloud/auth.md.
`
}

function base(ctx: TargetContext): Contribution[] {
  const renderer = ctx.target.mode
  if (!isRenderer(renderer)) throw new Error(`SpawnKit has no renderer named ${renderer}.`)
  const name = ctx.project.name
  const dimension = ctx.target.has("3d") ? "3d" : "2d"
  const [main, ...more] = packages[renderer]
  return [
    set("package.json", "/name", name),
    set("package.json", "/version", "0.0.0"),
    set("package.json", "/private", true),
    set("package.json", "/type", "module"),
    set("package.json", "/packageManager", "pnpm@12.10.1"),
    set("package.json", "/engines", { node: ">=24.0.0" }),
    { kind: "script", name: "dev", command: "dev-domains run app" },
    { kind: "script", name: "build", command: "tsc --noEmit && vite build" },
    { kind: "script", name: "preview", command: "vite preview" },
    { kind: "script", name: "lint", command: "oxlint --no-ignore src vite.config.ts" },
    { kind: "dependency", name: main, version: ctx.version(main) },
    ...more.map((pkg): Contribution => ({ kind: "dependency", name: pkg, version: ctx.version(pkg), dev: true })),
    ...["typescript", "vite", "oxlint", "oxfmt", "@buildkitgg/dev-domains", "@types/node"].map((pkg): Contribution => ({
      kind: "dependency",
      name: pkg,
      version: ctx.version(pkg),
      dev: true
    })),
    ...Object.entries({
      target: "ES2023",
      lib: ["ES2023", "DOM", "DOM.Iterable"],
      module: "ESNext",
      moduleResolution: "Bundler",
      strict: true,
      skipLibCheck: true,
      noEmit: true,
      isolatedModules: true,
      esModuleInterop: true
    }).map(([option, value]) => set("tsconfig.json", `/compilerOptions/${option}`, value)),
    { kind: "json", path: "tsconfig.json", pointer: "/compilerOptions/types", op: "append", value: "vite/client" },
    ...["src", "spawnkit.config.ts", "spawnkit", "vite.config.ts"].map((path): Contribution => ({
      kind: "json",
      path: "tsconfig.json",
      pointer: "/include",
      op: "append",
      value: path
    })),
    set("game.config.json", "/schemaVersion", 1),
    set("game.config.json", "/platform", "web"),
    set("game.config.json", "/name", name),
    set("game.config.json", "/template", renderer),
    set("game.config.json", "/dimension", dimension),
    set("game.config.json", "/mode", "single-player"),
    set("game.config.json", "/build", { command: "pnpm build", output: "dist" }),
    { kind: "yaml", path: "pnpm-workspace.yaml", pointer: "/packages", op: "set", value: [] },
    {
      kind: "lines",
      path: ".gitignore",
      lines: ["node_modules/", "dist/", ".env", ".env.*", "!.env.example", "coverage/", ".vitest/"]
    },
    {
      kind: "lines",
      path: ".gitattributes",
      lines: [`${gameFile} linguist-generated`, ".spawn/lock.json linguist-generated"]
    },
    { kind: "lines", path: ".npmrc", lines: ["engine-strict=true"] },
    seed("dev-domains.config.mjs", localDevelopmentFiles["dev-domains.config.mjs"]),
    owned("scripts/local-environment.mjs", localDevelopmentFiles["scripts/local-environment.mjs"]),
    owned("scripts/local-environment.d.mts", localDevelopmentFiles["scripts/local-environment.d.mts"]),
    seed(".oxlintrc.json", json({ categories: { correctness: "error" }, ignorePatterns: ["dist/**"] })),
    seed(".oxfmtrc.json", json({ semi: false, ignorePatterns: ["dist/**", "pnpm-lock.yaml"] })),
    seed("src/score.ts", "export function advanceScore(score: number): number {\n  return score + 1\n}\n"),
    seed("src/input.ts", inputSource),
    seed("src/main.ts", mainSources[renderer]),
    seed(
      "src/style.css",
      "* { box-sizing: border-box; }\nbody { margin: 0; background: #0a141c; color: #e7f0f5; font-family: system-ui, sans-serif; }\nheader { padding: 18px 24px; display: flex; gap: 20px; align-items: baseline; flex-wrap: wrap; }\nh1 { margin: 0; font-size: 20px; }\np { margin: 0; color: #a1b6c5; }\n#game { height: calc(100dvh - 100px); min-height: 300px; }\ncanvas { display: block; width: 100%; height: 100%; touch-action: none; }\n"
    ),
    seed(
      "vite.config.ts",
      'import { defineConfig } from "vite"\nimport { spawnkitListing } from "./spawnkit/vite"\n\nexport default defineConfig({ plugins: [spawnkitListing()], build: { target: "es2022" } })\n'
    ),
    seed(
      "index.html",
      `<!doctype html>\n<html lang="en">\n<head><meta charset="UTF-8" /><meta name="viewport" content="width=device-width, initial-scale=1" /><title>${name}</title></head>\n<body><header><h1>${name}</h1><p>Use the arrow keys to collect gold.</p><span id="score" aria-live="polite"></span></header><main id="game" aria-label="Game canvas"></main><script type="module" src="/src/main.ts"></script></body>\n</html>\n`
    ),
    seed(
      "spawnkit.config.ts",
      'import { defineConfig } from "./spawnkit/config"\n\nexport default defineConfig(' +
        JSON.stringify(
          {
            title: name,
            description: `Play ${name}, a new browser game made with SpawnKit.`,
            genre: "Arcade",
            dimension: dimension.toUpperCase(),
            coverPath: "media/cover.svg"
          },
          null,
          2
        ) +
        ")\n"
    ),
    owned("spawnkit/config.ts", listingConfigSource),
    owned("spawnkit/vite.ts", listingPluginSource),
    owned("spawnkit/runtime.ts", runtimeSource(renderer)),
    owned("spawnkit.config.schema.json", json(listingSchema)),
    sample("public/media/cover.svg", defaultCover),
    sample("README.md", readme(name, renderer)),
    sample("AGENTS.md", agents(name, renderer))
  ]
}

