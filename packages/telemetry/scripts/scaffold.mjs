import { readdir, readFile, writeFile } from "node:fs/promises"
import { resolve, dirname } from "node:path"
import { fileURLToPath } from "node:url"

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..")
const files = {}
for (const file of (await readdir(resolve(root, "dist"))).sort()) {
  if (!file.endsWith(".js") && !file.endsWith(".d.ts")) continue
  if (file.startsWith("otel.")) continue
  files[`vendor/spawn-telemetry/dist/${file}`] = await readFile(resolve(root, "dist", file), "utf8")
}
files["vendor/spawn-telemetry/package.json"] =
  JSON.stringify(
    {
      name: "@spawn/telemetry",
      version: "0.1.0",
      type: "module",
      private: true,
      sideEffects: false,
      exports: { ".": { types: "./dist/index.d.ts", import: "./dist/index.js" } }
    },
    null,
    2
  ) + "\n"
await writeFile(
  resolve(root, "scaffold.js"),
  `// Generated by packages/telemetry/scripts/scaffold.mjs. Rebuild the SDK to update.\nexport const telemetryFiles = ${JSON.stringify(files, null, 2)}\n`
)
await writeFile(resolve(root, "scaffold.d.ts"), "export declare const telemetryFiles: Record<string, string>\n")
