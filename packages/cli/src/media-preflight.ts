import { parse } from "@babel/parser"

export async function checkListingMedia(
  files: readonly { path: string; size: number }[],
  read: (path: string) => Promise<string>
) {
  const notices: string[] = []
  const typed = files.find((file) => file.path === "spawnkit.config.ts")
  const sources = files.filter((file) => ["spawnkit.config.ts", "spawnkit.config.json"].includes(file.path))
  if (sources.length > 1) throw new Error("Choose one listing source: spawnkit.config.ts or spawnkit.config.json.")
  const config = sources[0]
  if (!config) return notices
  if (config.size > 64 * 1024) throw new Error("Listing configuration exceeds 64 KiB.")
  const source = await read(config.path)
  let listing: Record<string, unknown> = {}
  if (typed) {
    // Parse syntax only. Deployment planning must never execute a creator's config or imports.
    const document = parse(source, { sourceType: "module", plugins: ["typescript"] })
    const exported = document.program.body.find((node) => node.type === "ExportDefaultDeclaration")
    const call = exported?.type === "ExportDefaultDeclaration" ? exported.declaration : null
    const object =
      call?.type === "CallExpression" && call.callee.type === "Identifier" && call.callee.name === "defineConfig"
        ? call.arguments[0]
        : null
    if (
      object?.type !== "ObjectExpression" ||
      object.properties.some((property) => property.type !== "ObjectProperty" || property.computed)
    )
      return ["Dynamic listing configuration: media checks will run on SpawnKit after the build."]
    for (const property of object.properties) {
      if (property.type !== "ObjectProperty") continue
      const key =
        property.key.type === "Identifier"
          ? property.key.name
          : property.key.type === "StringLiteral"
            ? property.key.value
            : ""
      if (!["coverPath", "trailerPath"].includes(key)) continue
      if (property.value.type === "StringLiteral") listing[key] = property.value.value
      else {
        delete listing[key]
        notices.push(`${key} is dynamic; SpawnKit will validate it after the build.`)
      }
    }
  } else {
    const value: unknown = JSON.parse(source)
    if (!value || typeof value !== "object" || Array.isArray(value)) throw new Error("Listing must be a JSON object.")
    listing = value as Record<string, unknown>
  }
  for (const kind of ["cover", "trailer"] as const) {
    const value = listing[`${kind}Path`]
    if (value === undefined || value === null || value === "") continue
    const extension = kind === "cover" ? /\.(png|jpe?g|webp|svg)$/ : /\.(mp4|webm)$/
    if (
      typeof value !== "string" ||
      value.length > 200 ||
      !/^[A-Za-z0-9_-][A-Za-z0-9_./-]*$/.test(value) ||
      !extension.test(value) ||
      value.split("/").some((part) => !part || part === "." || part === "..")
    )
      throw new Error(`Invalid ${kind} path. Use a supported release-relative path without public/ or a leading slash.`)
    const file = files.find((file) => file.path === `public/${value}`)
    if (!file) {
      notices.push(
        `${kind === "cover" ? "Cover" : "Trailer"} public/${value} is absent from the upload (check path, case and .spawnignore). If generated by your build, SpawnKit will validate it afterward.`
      )
      continue
    }
    const limit = (kind === "cover" ? 1 : 2) * 1024 * 1024
    if (file.size === 0 || file.size > limit)
      throw new Error(
        `${kind === "cover" ? "Cover" : "Trailer"} ${file.path} is ${file.size.toLocaleString("en-US")} bytes; limit ${kind === "cover" ? 1 : 2} MiB. Resize or compress it before deploying. No source was uploaded.`
      )
  }
  return notices
}
